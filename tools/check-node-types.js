#!/usr/bin/env node
"use strict";

const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");
const pinnedVersion = require(path.join(root, "package.json")).devDependencies["tree-sitter-cli"];

function checkGeneratedArtifacts(nodeTypesText, parserText) {
  if (!Array.isArray(JSON.parse(nodeTypesText))) {
    throw new Error("src/node-types.json must be a top-level array of node types.");
  }
  const banner = parserText.match(/^\/\* Automatically @generated by tree-sitter v([^\s*]+) \*\//);
  if (!banner || banner[1] !== pinnedVersion) {
    throw new Error(`src/parser.c generator version must match tree-sitter-cli ${pinnedVersion}.`);
  }
}

if (process.argv.includes("--self-test")) {
  const array = "[]";
  const matchingBanner = `/* Automatically @generated by tree-sitter v${pinnedVersion} */`;
  assert.doesNotThrow(() => checkGeneratedArtifacts(array, matchingBanner));
  assert.throws(() => checkGeneratedArtifacts('{"Ok":[]}', matchingBanner), /top-level array/);
  assert.throws(() => checkGeneratedArtifacts(array, "/* Automatically @generated by tree-sitter v0.0.0 */"), /generator version/);
  console.log("Generated artifact failure-path tests passed");
}

checkGeneratedArtifacts(
  fs.readFileSync(path.join(root, "src/node-types.json"), "utf8"),
  fs.readFileSync(path.join(root, "src/parser.c"), "utf8"),
);
